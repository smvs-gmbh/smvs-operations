"""Generate an audited CSV or Excel workbook from the exact rendered table cells supplied by the UI.

The browser retrieves pages through their original authorised GET routes. This
endpoint neither fetches arbitrary URLs nor interprets client-supplied SQL. An
export receipt records generated bytes, not proof that a file was saved locally.
"""

import csv
import hashlib
import io
import json
import logging
import re
from urllib.parse import urlsplit
from uuid import uuid4

from fastapi import APIRouter, HTTPException, Request
from fastapi.responses import Response
from fastapi.routing import APIRoute
from starlette.concurrency import run_in_threadpool

from app.domain.models import PortalCsvExport
from app.integration.artifacts.storage import utcnow
from app.portal.excel_export import XLSX_MIME, excel_bytes
from app.portal.routes import DbSession

logger = logging.getLogger(__name__)


class CsvAuditRoute(APIRoute):
    def get_route_handler(self):
        handler = super().get_route_handler()

        async def audited(request):
            try:
                return await handler(request)
            except Exception as exc:
                # Independent fallback when validation or the audit DB write fails.
                actor = getattr(request.state, "portal_user", None)
                logger.warning(
                    "Table export failed event=%s actor=%s UTC=%sZ HTTP=%s",
                    uuid4().hex, getattr(actor, "id", None), utcnow().isoformat(),
                    exc.status_code if isinstance(exc, HTTPException) else 500,
                )
                raise

        return audited


router = APIRouter(route_class=CsvAuditRoute)
MAX_REQUEST_BYTES = 50 * 1024 * 1024
MAX_CSV_BYTES = 100 * 1024 * 1024


def csv_cell(value):
    # Preserve text, including leading-zero identifiers. Never emit formulas.
    if value.lstrip().startswith(("=", "+", "-", "@")) or value.startswith(("\t", "\r")):
        return "'" + value
    return value


@router.post("/table-exports/xlsx", include_in_schema=False)
@router.post("/table-exports/csv", include_in_schema=False)
async def download_csv(request: Request, session: DbSession):
    file_format = request.url.path.rsplit("/", 1)[-1]
    actor = getattr(request.state, "portal_user", None)
    if not actor or not (getattr(actor, "is_nmvo", False) or getattr(actor, "is_admin", False)):
        raise HTTPException(403, "Sign in with an authorised staff account to download tables.")
    origin = urlsplit(str(request.url))
    if request.headers.get("origin") != f"{origin.scheme}://{origin.netloc}":
        raise HTTPException(403, "Use the download actions in the portal.")
    body = bytearray()
    async for chunk in request.stream():
        body.extend(chunk)
        if len(body) > MAX_REQUEST_BYTES:
            raise HTTPException(413, "This view is too large for one file. Narrow the view and try again.")
    try:
        data = json.loads(body)
        columns, rows = data["columns"], data["rows"]
        source, table_key, view_hash = data["source_path"], data["table_key"], data["view_hash"]
        if (
            not isinstance(columns, list) or not 1 <= len(columns) <= 100
            or any(not isinstance(c, dict) or not {"key", "label"} <= set(c) or not set(c) <= {"key", "label", "type"}
                   or not isinstance(c["key"], str) or not re.fullmatch(r"[A-Za-z0-9_-]{1,100}", c["key"])
                   or not isinstance(c["label"], str) or len(c["label"]) > 200 or c.get("type", "text") not in ("text", "number") for c in columns)
            or len({c["key"] for c in columns}) != len(columns)
            or not isinstance(rows, list) or len(rows) > 400000
            or any(not isinstance(row, list) or len(row) != len(columns)
                   or any(not isinstance(value, str) or len(value) > 1000000 for value in row) for row in rows)
            or not isinstance(source, str) or len(source) > 500
            or not source.startswith("/") or source.startswith("//")
            or urlsplit(source).query or urlsplit(source).fragment
            or any(ord(ch) < 32 for ch in source)
            or not isinstance(table_key, str) or not re.fullmatch(r"[A-Za-z0-9_-]{1,100}", table_key)
            or not isinstance(view_hash, str) or not re.fullmatch(r"[a-f0-9]{64}", view_hash)
        ):
            raise ValueError()
    except (ValueError, TypeError, KeyError, UnicodeDecodeError):
        raise HTTPException(422, "The table could not be exported. Reload the view and try again.") from None
    # An administrator without the NMVO role can export their administrative views.
    if not getattr(actor, "is_nmvo", False) and not any(
        source == prefix or source.startswith(prefix + "/")
        for prefix in ("/admin", "/imports", "/intelligence")
    ):
        raise HTTPException(403, "This role cannot export that view.")
    if file_format == "xlsx":
        try:
            content = await run_in_threadpool(excel_bytes, columns, rows)
        except ValueError as exc:
            raise HTTPException(422, str(exc)) from None
    else:
        output = io.StringIO(newline="")
        writer = csv.writer(output, quoting=csv.QUOTE_ALL, lineterminator="\r\n")
        writer.writerow([csv_cell(c["label"]) for c in columns])
        for row in rows:
            writer.writerow([csv_cell(value) for value in row])
            if output.tell() > MAX_CSV_BYTES:
                raise HTTPException(413, "This view is too large for one file. Narrow the view and try again.")
        content = output.getvalue().encode("utf-8-sig")
    if len(content) > MAX_CSV_BYTES:
        raise HTTPException(413, "This view is too large for one file. Narrow the view and try again.")
    now = utcnow()
    receipt = PortalCsvExport(
        actor_id=actor.id, created_at=now, source_path=source, table_key=table_key,
        columns=columns, view_hash=view_hash, row_count=len(rows), byte_count=len(content),
        file_sha256=hashlib.sha256(content).hexdigest(), file_format=file_format,
    )
    session.add(receipt)
    session.commit()  # Do not release a file if its audit receipt cannot be retained.
    filename = f"{table_key}-{now.strftime('%Y-%m-%d-%H%M%S')}-UTC.{file_format}"
    return Response(content, media_type=XLSX_MIME if file_format == "xlsx" else "text/csv; charset=utf-8", headers={
        "Content-Disposition": f'attachment; filename="{filename}"',
        "Cache-Control": "no-store", "X-Content-Type-Options": "nosniff",
        "X-Export-Receipt": str(receipt.id),
    })
